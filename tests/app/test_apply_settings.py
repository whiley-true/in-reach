def test_script_settings_text_mirrors_are_ignored(tmp_path: Path, top_level_key: str, entry: dict) -> None:
    # forge_labels[].name / scripted_player_traits[].name+desc are resolved script_strings-table
    # lookups computed only at extraction time (settings_writer.py's own module docstring: "Text
    # fields ... are deliberately NOT applied by this module at all") -- renaming the backing entry
    # via strings.json leaves these settings.json mirrors stale forever, same as team names.
    folder = _make_project(tmp_path)
    old_entry = dict(entry)
    new_entry = {**entry, "name": "new", **({"desc": "new"} if "desc" in entry else {})}
    (folder / "settings" / "script_settings.json").write_text(json.dumps({top_level_key: [old_entry]}), encoding="utf-8")
    (folder / "build" / "script_settings.autogenerated.json").write_text(
        json.dumps({top_level_key: [new_entry]}), encoding="utf-8"
    )

    assert apply_settings.settings_have_unapplied_changes(folder) is False


