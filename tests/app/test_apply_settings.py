@_NEEDS_NATIVE_RVT
def test_renaming_a_blank_script_string_leaves_nothing_pending(_project: tuple[Path, Path]) -> None:
    # Setting a previously-blank script_strings entry's text (bare-string shorthand) also feeds
    # script_settings.json's own scripted_options[].values[].desc mirror (resolved from the same
    # string-table index) -- that mirror used to stay stale after Apply too.
    project_dir, folder = _project
    strings_path = folder / "settings" / "strings.json"
    strings_data = _read_json(strings_path)
    blank_index = next(
        entry["index"]
        for entry in strings_data["script_strings"]
        if not (isinstance(entry["text"], dict) and any(entry["text"].values()))
    )
    entry = next(e for e in strings_data["script_strings"] if e["index"] == blank_index)
    entry["text"] = "Brand New Label"
    _write_json(strings_path, strings_data)

    result = apply_settings.apply_settings_changes(project_dir, folder)

    assert result.success is True
    assert apply_settings.settings_have_unapplied_changes(folder) is False


